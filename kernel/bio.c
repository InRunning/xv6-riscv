// 缓冲区缓存。
//
// 缓冲区缓存是一个 `buf` 结构的链表，其中包含磁盘块内容的缓存副本。
// 在内存中缓存磁盘块可以减少磁盘读取的次数，并为多个进程使用的磁盘块提供一个同步点。
//
// 接口说明:
// * 要获取特定磁盘块的缓冲区，请调用 bread。
// * 更改缓冲区数据后，调用 bwrite 将其写入磁盘。
// * 使用完缓冲区后，调用 brelse。
// * 调用 brelse 后，请勿再使用该缓冲区。
// * 同一时间只有一个进程可以使用一个缓冲区，因此不要占用超过必要的时间。

// 1. 头文件 ----
#include "types.h"
#include "param.h"
#include "spinlock.h"
#include "sleeplock.h"
#include "riscv.h"
#include "defs.h"
#include "fs.h"
#include "buf.h"

// 2. 全局变量 ----
struct
{
  struct spinlock lock;
  struct buf buf[NBUF];

  // 所有缓冲区的链表，通过 prev/next 连接。
  // 按最近使用的顺序排序。
  // head.next 是最近使用的，head.prev 是最久未使用的。
  struct buf head;
} bcache;

// 3. 函数 ----

// 3.1. 初始化 ----
// 3.1. 初始化 ----
// binit 函数：初始化缓冲区缓存。
// 该函数在系统启动时调用一次，用于设置缓冲区缓存的数据结构。
void binit(void)
{
  struct buf *b;

  // 初始化 bcache 的自旋锁，用于保护整个缓冲区缓存的元数据（如链表结构）。
  initlock(&bcache.lock, "bcache");

  // 创建一个循环双向链表来管理所有缓冲区。
  // bcache.head 是一个哨兵节点，它不存储实际的磁盘数据，
  // 而是作为链表的头尾，简化了链表操作的边界条件。
  bcache.head.prev = &bcache.head;
  bcache.head.next = &bcache.head;

  // 遍历所有的缓冲区 `bcache.buf[NBUF]`，将它们添加到链表中。
  // 初始时，所有缓冲区都按顺序添加到链表的头部，
  // 使得 `bcache.head.next` 指向最近添加的缓冲区，
  // `bcache.head.prev` 指向最先添加的缓冲区（即最久未使用的）。
  // NBUF (Number of Buffers) 定义了磁盘块缓存中缓冲区的数量，目前是一个常量30
  for (b = bcache.buf; b < bcache.buf + NBUF; b++)
  {
    // 将当前缓冲区 b 插入到链表的头部，使其成为新的最最近使用的缓冲区。
    // 具体操作是将 b 放在 bcache.head 和原来的 bcache.head.next 之间。
    b->next = bcache.head.next; // b 的 next 指向当前链表的第一个元素
    b->prev = &bcache.head;     // b 的 prev 指向链表头（哨兵节点）
    // 初始化每个缓冲区的睡眠锁，用于保护缓冲区的数据内容。
    // 当一个进程正在读写某个缓冲区时，其他进程需要等待该锁。
    initsleeplock(&b->lock, "buffer");
    // 更新链表中相邻节点的指针，完成双向链表的插入。
    bcache.head.next->prev = b; // 原来的第一个元素的 prev 现在指向 b
    bcache.head.next = b;       // 链表头的 next 现在指向 b，使 b 成为新的第一个元素
  }
}
// 3.2. 缓冲区管理 ----

// bget (Buffer Get) - 获取或分配缓冲区
//
// 功能说明：
// 该函数是xv6缓冲区缓存系统的核心函数，负责在缓冲区缓存中查找指定磁盘块，
// 如果未找到则分配一个新缓冲区。无论哪种情况，都返回一个已锁定的缓冲区。
//
// 参数：
//   - dev: 设备号，标识要访问的磁盘设备
//          在xv6中，每个磁盘设备都有一个唯一的设备号
//          例如：ROOTDEV(1)是根文件系统所在的磁盘设备
//          设备号用于区分系统中的多个磁盘设备（如主磁盘、从磁盘等）
//   - blockno: 块号，标识要访问的磁盘块在设备上的逻辑位置
//
// 返回值：
//   返回一个指向struct buf的指针，该缓冲区：
//   1. 已被锁定（持有睡眠锁）
//   2. 引用计数已增加
//   3. 如果是新分配的缓冲区，valid标志设为0（数据无效）
//   4. 如果是已缓存的缓冲区，保持原有valid状态
//
// 工作流程：
//   1. 获取bcache的自旋锁，保护整个缓冲区缓存的元数据
//   2. 在缓冲区链表中搜索指定设备和块号的缓冲区
//      - 链表按LRU（最近最少使用）顺序组织
//      - 从head.next（最近使用）开始搜索到head.prev（最久未使用）
//   3. 如果找到匹配的缓冲区：
//      - 增加引用计数(refcnt++)
//      - 释放bcache自旋锁
//      - 获取缓冲区的睡眠锁
//      - 返回缓冲区指针
//   4. 如果未找到匹配的缓冲区：
//      - 从链表尾部（最久未使用）开始搜索空闲缓冲区
//      - 空闲缓冲区的判断标准是refcnt==0（无进程引用）
//      - 找到空闲缓冲区后，重新初始化其元数据
//      - 释放bcache自旋锁
//      - 获取缓冲区的睡眠锁
//      - 返回缓冲区指针
//   5. 如果没有空闲缓冲区可用，触发panic（系统崩溃）
//
// 注意事项：
//   - 该函数使用两种锁：自旋锁保护元数据，睡眠锁保护缓冲区数据
//   - 自旋锁持有时间很短，仅用于保护链表操作
//   - 睡眠锁可能长时间持有，允许进程在等待磁盘I/O时被调度
//   - LRU策略确保频繁访问的块保留在缓存中
//   - 新分配的缓冲区valid=0，表示数据无效，需要从磁盘读取
static struct buf *
bget(uint dev, uint blockno)
{
  struct buf *b;

  // 获取bcache的自旋锁，保护整个缓冲区缓存的元数据（如链表结构）
  // 自旋锁用于短时间临界区，不允许进程睡眠
  acquire(&bcache.lock);

  // 第一阶段：在缓冲区缓存中查找指定设备和块号的块是否已经被缓存
  // 遍历缓冲区链表，从最近使用的(head.next)开始查找
  for (b = bcache.head.next; b != &bcache.head; b = b->next)
  {
    // 检查当前缓冲区是否匹配指定的设备和块号
    // dev比较确保缓冲区来自正确的磁盘设备，dev是device的简写
    // 在xv6中，可以有多个磁盘设备，每个设备都有自己的设备号
    // 例如：ROOTDEV(1)是根文件系统磁盘，其他设备可能有不同的设备号
    if (b->dev == dev && b->blockno == blockno)
    {
      // 找到匹配的缓冲区，增加引用计数
      // refcnt表示有多少个进程正在使用该缓冲区
      b->refcnt++;

      // 释放bcache的自旋锁，不再需要保护链表结构
      release(&bcache.lock);
      
      // 获取缓冲区的睡眠锁，保护缓冲区的数据内容
      // 睡眠锁的作用和必要性：
      // 1. 互斥访问：确保同一时间只有一个进程能访问该缓冲区的数据
      // 2. 磁盘I/O同步：当进程需要从磁盘读取数据时（如bread函数），
      //    可能需要等待磁盘I/O完成，此时进程会睡眠但保持锁
      // 3. 防止竞争：防止其他进程在当前进程正在读取或修改缓冲区数据时
      //    同时访问该缓冲区，导致数据不一致
      // 4. 睡眠机制：与自旋锁不同，睡眠锁允许进程在等待资源时进入睡眠状态，
      //    释放CPU给其他进程使用，提高系统效率
      // 5. 中断安全：磁盘I/O完成后，中断处理程序会唤醒等待的进程
      acquiresleep(&b->lock);
      
      // 返回已锁定的缓冲区指针
      return b;
    }
  }

  // 第二阶段：未找到缓存的块，需要分配一个新缓冲区
  // 从最久未使用的缓冲区开始搜索空闲缓冲区（LRU策略）
  // 从链表尾部(head.prev)开始遍历，这是最久未使用的缓冲区
  for (b = bcache.head.prev; b != &bcache.head; b = b->prev)
  {
    // 检查缓冲区是否空闲（引用计数为0）
    if (b->refcnt == 0)
    {
      // 找到空闲缓冲区，重新初始化其元数据
      b->dev = dev;         // 设置设备号，标识该缓冲区属于哪个磁盘设备
      b->blockno = blockno; // 设置块号，标识该缓冲区对应设备上的哪个逻辑块
      b->valid = 0;         // 标记数据无效，需要从磁盘读取
      b->refcnt = 1;        // 设置引用计数为1（当前进程）

      // 释放bcache的自旋锁
      release(&bcache.lock);
      
      // 获取缓冲区的睡眠锁
      // 同样需要获取睡眠锁的原因：
      // 1. 新分配的缓冲区即将被使用，必须确保独占访问
      // 2. 后续的bread()函数可能会从磁盘读取数据，需要等待I/O完成
      // 3. 即使是新分配的缓冲区，也要防止其他进程同时访问
      // 4. 保持与已缓存缓冲区的一致性，所有返回的缓冲区都是已锁定状态
      acquiresleep(&b->lock);
      
      // 返回新分配的缓冲区
      return b;
    }
  }

  // 如果没有找到空闲缓冲区，说明系统资源耗尽，触发panic
  // 这通常表示NBUF（缓冲区数量）设置过小或存在缓冲区泄漏
  panic("bget: no buffers");
}

// bread (Buffer Read) - 读取磁盘块到缓冲区
//
// 功能说明：
// 该函数用于从指定设备读取指定块号的磁盘块到内存缓冲区中。
// 这是xv6文件系统中磁盘I/O的核心函数，负责将磁盘数据加载到内存缓存中。
//
// 参数：
//   - dev: 设备号，标识要读取的磁盘设备
//   - blockno: 块号，标识要读取的磁盘块在设备上的逻辑位置
//
// 返回值：
//   返回一个指向struct buf的指针，该缓冲区包含：
//   1. 已锁定的缓冲区（持有睡眠锁）
//   2. 包含指定磁盘块内容的data数组
//   3. valid标志设置为1，表示数据已从磁盘读取
//
// 工作流程：
//   1. 调用bget()获取或分配一个缓冲区
//      - 如果该块已在缓存中，返回现有缓冲区并增加引用计数
//      - 如果不在缓存中，分配一个LRU缓冲区并标记为无效(valid=0)
//   2. 检查缓冲区的valid标志
//      - 如果valid=1，表示数据已在内存中，无需从磁盘读取
//      - 如果valid=0，表示数据无效，需要从磁盘读取
//   3. 当数据无效时，调用virtio_disk_rw()从磁盘读取数据
//      - 第二个参数0表示读操作（1表示写操作）
//      - 该函数会阻塞直到磁盘读取完成
//   4. 设置valid=1，标记缓冲区数据有效
//   5. 返回缓冲区指针
//
// 注意事项：
//   - 返回的缓冲区已被锁定，调用者持有睡眠锁
//   - 使用完缓冲区后必须调用brelse()释放锁和缓冲区
//   - 如果要修改缓冲区内容，修改后需调用bwrite()写回磁盘
//   - 多个进程可以同时读取同一块，但只有一个进程会触发实际的磁盘读取
struct buf *
bread(uint dev, uint blockno)
{
  struct buf *b;

  // 获取或分配一个缓冲区，该缓冲区已被锁定
  // bget()会：
  // 1. 在缓冲区缓存中查找指定设备和块号的缓冲区
  // 2. 如果找到，增加引用计数并返回
  // 3. 如果未找到，从LRU链表尾部分配一个未使用的缓冲区
  // 4. 设置缓冲区的dev和blockno，并将valid设为0
  // 5. 获取缓冲区的睡眠锁并返回
  b = bget(dev, blockno);

  // 检查缓冲区数据是否有效
  // valid=1表示缓冲区中的数据是从磁盘读取的最新数据
  // valid=0表示缓冲区数据无效（可能是新分配的或已被修改但未写回）
  if (!b->valid)
  {
    // 如果数据无效，从磁盘读取数据到缓冲区
    // virtio_disk_rw()是底层磁盘驱动函数，通过virtio接口与磁盘设备通信
    // 第二个参数0表示读操作（1表示写操作）
    // 该函数会阻塞直到磁盘读取完成，通过中断机制唤醒等待的进程
    virtio_disk_rw(b, 0);

    // 标记缓冲区数据有效，表示数据已从磁盘读取
    // 这样后续的bread()调用就不需要再次从磁盘读取
    b->valid = 1;
  }

  // 返回包含有效数据的锁定缓冲区
  // 调用者现在可以安全地访问b->data中的磁盘块内容
  return b;
}

// 将缓冲区 b 的内容写入磁盘。必须持有锁。
void bwrite(struct buf *b)
{
  if (!holdingsleep(&b->lock))
    panic("bwrite");
  virtio_disk_rw(b, 1);
}

// brelse (Buffer Release) - 释放缓冲区
//
// 功能说明：
// 该函数用于释放一个已锁定的缓冲区，将其返回到缓冲区缓存中。
// 这是xv6缓冲区缓存系统的重要函数，负责管理缓冲区的生命周期和LRU（最近最少使用）策略。
//
// 参数：
//   - b: 指向要释放的缓冲区的指针
//       该缓冲区必须已被锁定（持有睡眠锁）
//
// 返回值：
//   无返回值（void）
//
// 工作流程：
//   1. 检查缓冲区是否被锁定（持有睡眠锁）
//      - 如果未被锁定，触发panic（程序异常终止）
//      - 这是安全检查，防止释放未锁定的缓冲区
//   2. 释放缓冲区的睡眠锁
//      - 允许其他进程访问该缓冲区
//      - 睡眠锁（sleeplock）用于保护缓冲区的数据内容
//   3. 获取bcache的自旋锁，保护缓冲区缓存的元数据
//      - 自旋锁（spinlock）用于保护链表结构等元数据
//   4. 减少缓冲区的引用计数（refcnt--）
//      - 引用计数表示有多少个进程正在使用该缓冲区
//   5. 如果引用计数变为0（没有进程在使用）：
//      - 将缓冲区从当前位置移除（从LRU链表中删除）
//      - 将缓冲区移动到链表头部（最近使用位置）
//      - 实现LRU缓存替换策略
//   6. 释放bcache的自旋锁
//
// LRU策略实现细节：
//   - 当refcnt==0时，缓冲区被重新插入到链表头部
//   - 链表头部（head.next）是最近使用的缓冲区
//   - 链表尾部（head.prev）是最久未使用的缓冲区
//   - 这种设计确保频繁访问的块保留在缓存中
//   - 当需要替换缓冲区时，优先替换最久未使用的块
//
// 锁的使用说明：
//   - 睡眠锁：保护缓冲区的数据内容，允许进程在等待I/O时睡眠
//   - 自旋锁：保护缓冲区缓存的元数据（如链表结构），短时间持有
//
// 注意事项：
//   - 调用此函数前必须确保已持有缓冲区的睡眠锁
//   - 释放缓冲区后，不应再访问该缓冲区的数据
//   - 该函数是bread()函数的配对函数，使用完缓冲区后必须调用
//   - 引用计数机制确保缓冲区在仍有进程使用时不会被回收
//
// 错误处理：
//   - 如果缓冲区未被锁定（!holdingsleep(&b->lock)），触发panic
//   - 这表示程序逻辑错误，可能是未正确获取锁就尝试释放
//
// 性能考虑：
//   - 自旋锁持有时间很短，仅用于保护链表操作
//   - 睡眠锁的释放允许其他进程立即访问缓冲区
//   - LRU更新操作在O(1)时间内完成，效率较高
void brelse(struct buf *b)
{
  // 检查缓冲区是否被锁定（持有睡眠锁）
  // holdingsleep()函数检查当前进程是否持有指定睡眠锁
  // 如果未被锁定，说明程序逻辑错误，触发panic
  // brelse是buffer release的简写，释放缓冲区的意思
  if (!holdingsleep(&b->lock))
    panic("brelse");

  // 释放缓冲区的睡眠锁
  // releasesleep()函数释放指定的睡眠锁
  // 释放后，其他进程可以获取该锁并访问缓冲区数据
  // 睡眠锁的作用是保护缓冲区的数据内容，确保独占访问
  releasesleep(&b->lock);

  // 获取bcache的自旋锁，保护缓冲区缓存的元数据
  // acquire()函数获取自旋锁，用于保护链表结构等共享数据
  // 自旋锁用于短时间临界区，不允许进程睡眠
  acquire(&bcache.lock);
  
  // 减少缓冲区的引用计数（reference count）
  // refcnt表示有多少个进程正在使用或等待该缓冲区
  // 每次调用bread()会增加refcnt，每次调用brelse会减少refcnt
  b->refcnt--;
  
  // 检查引用计数是否变为0（没有进程在使用该缓冲区）
  if (b->refcnt == 0)
  {
    // 没有进程在等待它，可以安全地重新排列缓冲区位置
    // 这部分代码实现了LRU（最近最少使用）缓存策略
    
    // 第一步：从当前位置移除缓冲区
    // 更新后一个节点的prev指针，跳过当前缓冲区
    b->next->prev = b->prev;
    // 更新前一个节点的next指针，跳过当前缓冲区
    b->prev->next = b->next;
    
    // 第二步：将缓冲区移动到链表头部（最近使用位置）
    // 设置当前缓冲区的next指针指向原来的第一个元素
    b->next = bcache.head.next;
    // 设置当前缓冲区的prev指针指向链表头（哨兵节点）
    b->prev = &bcache.head;
    
    // 第三步：更新链表头部，使当前缓冲区成为新的第一个元素
    // 原来第一个元素的prev指针现在指向当前缓冲区
    bcache.head.next->prev = b;
    // 链表头的next指针现在指向当前缓冲区
    bcache.head.next = b;
  }

  // 释放bcache的自旋锁
  // release()函数释放自旋锁，允许其他进程访问缓冲区缓存
  release(&bcache.lock);
}

// 3.3. 引用计数 ----

// 增加缓冲区的引用计数，防止其被回收。
void bpin(struct buf *b)
{
  acquire(&bcache.lock);
  b->refcnt++;
  release(&bcache.lock);
}

// 减少缓冲区的引用计数。
void bunpin(struct buf *b)
{
  acquire(&bcache.lock);
  b->refcnt--;
  release(&bcache.lock);
}